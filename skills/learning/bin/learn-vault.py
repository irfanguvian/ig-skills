#!/usr/bin/env python3
"""Export .learning/graph.json (CONTRACT 2) + notes to an Obsidian vault. CONTRACT 3.

usage: learn-vault.py export [--learning DIR] [--out DIR] [--graph PATH]
  defaults: --learning .learning  --out <learning>/vault  --graph <learning>/graph.json

Per node: <out>/<type>/<id>.md = passthrough frontmatter + `cssclass: generated`, original body,
"## Prerequisites" (incoming prerequisite edges), "## Related" (symmetric related edges).
Empty sections omitted. <out>/index.md = MOC by tag, then type.
Idempotent, byte-identical. <out> deleted+regenerated (only if empty or carries .learning-vault marker).
Report: nodes, edges, dangling ids, orphans, prerequisite cycles (warning).
No LLM. Pure file transform.
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

MARKER = ".learning-vault"
FM_RE = re.compile(r"\A---\n(.*?)\n---\n?", re.S)


def split_note(text: str) -> tuple[str, str]:
    """-> (frontmatter inner lines text, body). Frontmatter raw, untouched."""
    m = FM_RE.match(text)
    return (m.group(1), text[m.end():]) if m else ("", text)


def find_cycles(nodes: list[str], edges: list[tuple[str, str]]) -> list[list[str]]:
    """Simple cycles among prerequisite edges (directed). Deterministic order."""
    adj: dict[str, list[str]] = {n: [] for n in nodes}
    for a, b in edges:
        adj.setdefault(a, []).append(b)
        adj.setdefault(b, [])
    for k in adj:
        adj[k].sort()
    cycles: set[tuple[str, ...]] = set()
    WHITE, GRAY, BLACK = 0, 1, 2
    color = {n: WHITE for n in adj}
    stack: list[str] = []

    def dfs(u: str) -> None:
        color[u] = GRAY
        stack.append(u)
        for v in adj[u]:
            if color[v] == GRAY:
                cyc = stack[stack.index(v):]
                k = cyc.index(min(cyc))
                cycles.add(tuple(cyc[k:] + cyc[:k]))
            elif color[v] == WHITE:
                dfs(v)
        stack.pop()
        color[u] = BLACK

    for n in sorted(adj):
        if color[n] == WHITE:
            dfs(n)
    return [list(c) for c in sorted(cycles)]


def export(learning: Path, out: Path, graph_path: Path | None = None) -> dict:
    learning = learning.resolve()
    out = out.resolve()
    graph_path = (graph_path or learning / "graph.json").resolve()
    g = json.loads(graph_path.read_text(encoding="utf-8"))
    nodes = {n["id"]: n for n in g["nodes"]}
    edges = [(e["from"], e["to"], e["rel"]) for e in g["edges"]]

    # analysis
    dangling = sorted({x for a, b, _ in edges for x in (a, b) if x not in nodes})
    touched = {x for a, b, _ in edges for x in (a, b)}  # dangling edge still counts as an edge
    orphans = sorted(i for i in nodes if i not in touched)
    pre_edges = [(a, b) for a, b, r in edges if r == "prerequisite" and a in nodes and b in nodes]
    cycles = find_cycles(sorted(nodes), pre_edges)

    # guard: only wipe what we made
    if out.exists():
        if out.is_file():
            raise SystemExit(f"learn-vault: {out} is a file")
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise SystemExit(f"learn-vault: refuse to delete {out}: not empty and no {MARKER} marker")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("generated by learn-vault.py — do not hand-edit\n", encoding="utf-8")

    incoming_pre: dict[str, set[str]] = {i: set() for i in nodes}
    related: dict[str, set[str]] = {i: set() for i in nodes}
    for a, b, r in edges:
        if r == "prerequisite" and b in nodes:
            incoming_pre[b].add(a)
        elif r == "related":
            if a in nodes:
                related[a].add(b)
            if b in nodes:
                related[b].add(a)

    for i, n in sorted(nodes.items()):
        src = learning / n["path"]
        fm_raw, body = split_note(src.read_text(encoding="utf-8", errors="replace")) if src.exists() else ("", f"(missing source {n['path']})\n")
        fm_lines = [l for l in fm_raw.splitlines() if not l.startswith("cssclass:")]
        fm_lines.append("cssclass: generated")
        parts = ["---", *fm_lines, "---", body.rstrip("\n"), ""]
        if incoming_pre[i]:
            parts += ["## Prerequisites", *[f"- [[{x}]]" for x in sorted(incoming_pre[i])], ""]
        if related[i]:
            parts += ["## Related", *[f"- [[{x}]]" for x in sorted(related[i])], ""]
        d = out / n["type"]
        d.mkdir(exist_ok=True)
        (d / f"{i}.md").write_text("\n".join(parts).rstrip("\n") + "\n", encoding="utf-8")

    # index.md — MOC by tag, then type
    by_tag: dict[str, dict[str, list[str]]] = {}
    for i, n in nodes.items():
        for t in (n.get("tags") or ["(untagged)"]):
            by_tag.setdefault(t, {}).setdefault(n["type"], []).append(i)
    lines = ["---", "id: index", "title: Index", "type: moc", "tags: [index]", "cssclass: generated", "---", "# Index", ""]
    for t in sorted(by_tag):
        lines.append(f"## {t}")
        for ty in sorted(by_tag[t]):
            lines.append(f"### {ty}")
            lines += [f"- [[{i}]] {nodes[i]['title']}" for i in sorted(by_tag[t][ty])]
        lines.append("")
    (out / "index.md").write_text("\n".join(lines).rstrip("\n") + "\n", encoding="utf-8")

    return {"out": str(out), "nodes": len(nodes), "edges": len(edges), "dangling": dangling,
            "orphans": orphans, "cycles": cycles}


def main(argv: list[str]) -> int:
    if not argv or argv[0] != "export":
        print(__doc__, file=sys.stderr)
        return 1
    opts = {"--learning": ".learning", "--out": None, "--graph": None}
    i = 1
    while i < len(argv):
        if argv[i] in opts and i + 1 < len(argv):
            opts[argv[i]] = argv[i + 1]
            i += 2
        else:
            print(f"learn-vault: bad arg {argv[i]}", file=sys.stderr)
            return 1
    learning = Path(opts["--learning"])
    out = Path(opts["--out"]) if opts["--out"] else learning / "vault"
    r = export(learning, out, Path(opts["--graph"]) if opts["--graph"] else None)
    # outside .learning? make sure git ignores it
    try:
        out.resolve().relative_to(learning.resolve())
    except ValueError:
        gi = Path(".gitignore")
        rel = out.resolve().relative_to(Path.cwd().resolve()).as_posix() + "/" if out.resolve().is_relative_to(Path.cwd().resolve()) else None
        if rel and (not gi.exists() or rel not in gi.read_text().splitlines()):
            with gi.open("a", encoding="utf-8") as f:
                f.write(rel + "\n")
            print(f"gitignore: added {rel}")
    print(f"vault: {r['out']}")
    print(f"nodes: {r['nodes']}  edges: {r['edges']}")
    print(f"dangling: {', '.join(r['dangling']) or 'none'}")
    print(f"orphans: {', '.join(r['orphans']) or 'none'}")
    print("cycles: " + ("; ".join(" -> ".join(c + [c[0]]) for c in r["cycles"]) if r["cycles"] else "none") + ("  (warning)" if r["cycles"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
